-- ============================================================
-- Quiz Results -- one row per completed quiz attempt. No
-- per-question/answer data is ever stored here. Run in Supabase's
-- SQL Editor.
-- ============================================================

create table public.quiz_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    attempt_uuid UUID NOT NULL UNIQUE,

    username TEXT NOT NULL,
    user_name TEXT NOT NULL,
    designation TEXT,
    hq TEXT,
    zone TEXT,

    asm_name TEXT,
    asm_hq TEXT,
    asm_email TEXT,

    rsm_name TEXT,
    rsm_hq TEXT,
    rsm_email TEXT,

    product_name TEXT NOT NULL,

    total_questions INTEGER NOT NULL,
    correct_answers INTEGER NOT NULL,
    score_percent NUMERIC(5,2) NOT NULL,

    total_time_seconds INTEGER NOT NULL,

    completed_at TIMESTAMPTZ NOT NULL,
    app_version TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT quiz_results_total_questions_positive
        CHECK (total_questions > 0),

    CONSTRAINT quiz_results_correct_answers_valid
        CHECK (
            correct_answers >= 0
            AND correct_answers <= total_questions
        ),

    CONSTRAINT quiz_results_score_valid
        CHECK (
            score_percent >= 0
            AND score_percent <= 100
        ),

    CONSTRAINT quiz_results_time_valid
        CHECK (total_time_seconds >= 0)
);

CREATE INDEX idx_quiz_results_username ON public.quiz_results(username);
CREATE INDEX idx_quiz_results_product ON public.quiz_results(product_name);
CREATE INDEX idx_quiz_results_completed_at ON public.quiz_results(completed_at DESC);
CREATE INDEX idx_quiz_results_asm_email ON public.quiz_results(asm_email);
CREATE INDEX idx_quiz_results_rsm_email ON public.quiz_results(rsm_email);

-- ============================================================
-- RLS
--
-- No Supabase Auth exists in this app (custom check_login RPC is used
-- instead), so there is no auth.uid() to scope rows by -- same
-- situation as every other table this app writes to. The anon key is
-- granted INSERT and UPDATE only:
--   - INSERT: the normal "save my completed quiz" path.
--   - UPDATE: required because the upsert-on-attempt_uuid retry path
--     performs an actual UPDATE under RLS whenever a conflict is found
--     (Postgres evaluates the UPDATE policy for the ON CONFLICT DO
--     UPDATE branch of an upsert, not just the INSERT policy).
--
-- Deliberately NO SELECT policy: nothing in the app currently reads
-- this table back (no in-app history/reporting screen exists yet), so
-- read access is left closed by default rather than granted
-- speculatively. Add one later if/when a reporting feature needs it.
-- ============================================================
alter table public.quiz_results enable row level security;

create policy "insert quiz results" on public.quiz_results
  for insert with check (true);

create policy "upsert quiz results on retry" on public.quiz_results
  for update using (true) with check (true);
